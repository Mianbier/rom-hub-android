/**
 * 首页 tips 条 —— **照抄 HyperCeiler 的 `headtip_*` 五种样式**（布局、背景、配色全是原版，
 * 见 `res/layout/headtip_{tip,warn,notice,hyperceiler,hyperceiler_birthday}.xml` 与
 * `res/drawable/headtip_*_background.xml`），只把**文案换成 HyperRomhub 自己的**。
 *
 * 每次进 App 随机挑一种样式 + 一条文案（同一进程内固定，不会来回闪）。
 * 文案见 [HcTips]，共 300 条，刻意混了冷知识 / 吐槽 / 提示 / 数据 / 问答 / 警告 / 彩蛋等写法。
 */
@Composable
fun HcHomeTip(modifier: Modifier = Modifier) {
    val pick = remember { TipStyle.entries.random() to HcTips.list.random() }

    AndroidView(
        modifier = modifier.fillMaxWidth(),
        factory = { ctx ->
            LayoutInflater.from(ctx).inflate(pick.first.layoutRes, null).also { v ->
                v.findViewById<TextView>(android.R.id.title)?.text = pick.second
            }
        },
    )
}

/** 五种样式（与 HyperCeiler 的 headtip 布局一一对应）。 */
private enum class TipStyle(val layoutRes: Int) {
    TIP(R.layout.headtip_tip),
    WARN(R.layout.headtip_warn),
    NOTICE(R.layout.headtip_notice),
    BRAND(R.layout.headtip_hyperceiler),
    BIRTHDAY(R.layout.headtip_hyperceiler_birthday),
}

